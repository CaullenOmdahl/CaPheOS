  if (opts.from === 'dispatch' && !ctx.dry) { const f = ctx.P('company/work/dispatch-state.json'); process.once('exit', () => { try { require('./provenance.js').wrote(f, fs.readFileSync(f), 'dispatch.js'); } catch (_) {} }); }
