const redact = s => String(s).replace(/[A-Za-z0-9+/=_-]{24,}/g, '…').replace(/[\r\n\u2028\u2029]+/g, ' ').slice(0, 90);
function jsonDiff(a, b, p, out) {
  if (out.length >= 6) return;
  if (JSON.stringify(a) === JSON.stringify(b)) return;
  if (a && b && typeof a === 'object' && typeof b === 'object' && !Array.isArray(a) && !Array.isArray(b)) { for (const k of new Set(Object.keys(a).concat(Object.keys(b)))) jsonDiff(a[k], b[k], p + '/' + k, out); return; }
  out.push(redact(p || '/') + ': ' + redact(a === undefined ? '(none)' : JSON.stringify(a)).slice(0, 40) + ' -> ' + redact(b === undefined ? '(none)' : JSON.stringify(b)).slice(0, 40));
}
function diffSummary(oldBuf, newBuf, m) {
  if (m && m.cls === 'K') return 'content or mode changed (keys are never shown)';
  if (!oldBuf && newBuf) return 'new file, ' + newBuf.length + ' bytes';
  if (oldBuf && !newBuf) return 'deleted (was ' + oldBuf.length + ' bytes)';
  if (!oldBuf || !newBuf) return 'changed';
  if (newBuf.length > 4e6 || oldBuf.length > 4e6) return 'changed: ' + oldBuf.length + ' -> ' + newBuf.length + ' bytes';
  const A = oldBuf.toString('utf8'), B = newBuf.toString('utf8');
  try { const ja = JSON.parse(A), jb = JSON.parse(B); const out = []; jsonDiff(ja, jb, '', out); if (out.length) return out.join('; '); } catch (_) {}
  const count = t => { const m2 = new Map(); for (const l of t.split('\n')) m2.set(l, (m2.get(l) || 0) + 1); return m2; };
  const ca = count(A), cb = count(B); const added = [], removed = [];
  for (const [l, n] of cb) for (let i = (ca.get(l) || 0); i < n; i++) added.push(l);
  for (const [l, n] of ca) for (let i = (cb.get(l) || 0); i < n; i++) removed.push(l);
  return '+' + added.length + '/-' + removed.length + ' lines' + (added.length ? '; added: "' + redact(added.find(x => x.trim()) || '') + '"' : '') + (removed.length ? '; removed: "' + redact(removed.find(x => x.trim()) || '') + '"' : '');
}

