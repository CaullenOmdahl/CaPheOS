// an ISO stamp in the company timezone (co.TZ) with its real offset, e.g. 2030-01-02T09:30:00+01:00
const local = ms => {
  const d = new Date(ms);
  const o = {}; for (const x of new Intl.DateTimeFormat('en-CA', { timeZone: co.TZ, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false }).formatToParts(d)) o[x.type] = x.value;
  const hh = String(Number(o.hour) % 24).padStart(2, '0');
  const off = Math.round((Date.UTC(+o.year, +o.month - 1, +o.day, +hh, +o.minute, +o.second) - Math.floor(ms / 1000) * 1000) / 60000);
  const a = Math.abs(off);
  return o.year + '-' + o.month + '-' + o.day + 'T' + hh + ':' + o.minute + ':' + o.second + (off < 0 ? '-' : '+') + String(Math.floor(a / 60)).padStart(2, '0') + ':' + String(a % 60).padStart(2, '0');
};
