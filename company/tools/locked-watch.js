// a shell command that WRITES (not a file-descriptor redirect like 2>/dev/null, &>, >&2, nor a read): tee/sed -i/mv/cp/rm/…,
// a node write call, or an output redirect `>`/`>>` to a real target (not /dev/null and not another fd)
// (the old WRITE_OP regex lived here: it answered "did the command mention a write verb", which is a question too wide
// to mean anything — `cp <key> scratch/<key>` names one and writes the file nowhere near it. Attribution now asks
// writesPath(), the same destination-aware function the self-accept check uses.)
const FILE_TOOLS = /^fs_(write|edit|append|patch|delete|move|rename|copy)/;
function pathsInArgs(a) {
  const out = [];
  if (a && typeof a.path === 'string') out.push(a.path);
  for (const k of ['from', 'to', 'src', 'dest', 'target']) if (a && typeof a[k] === 'string') out.push(a[k]);
  if (a && typeof a.patch === 'string') for (const line of a.patch.replace(/\r\n?/g, '\n').split('\n')) { let m; if ((m = /^\*\*\*\s*(?:Add|Update|Delete) File:\s*(.+?)\s*$/.exec(line)) || (m = /^\*\*\*\s*Move to:\s*(.+?)\s*$/.exec(line))) out.push(m[1]); else if ((m = /^\*\*\*\s*Move File:\s*(.+?)\s*->\s*(.+?)\s*$/.exec(line))) out.push(m[1], m[2]); }
  return out;
}
// one pass over the transcripts since fromMs: tool calls whose arguments name a needle. Only the tool name, agent, run and time
