const INSERT_WRITERS = ['decision.js'];
function decideRolled(ctx, key, m, b, cur, prov, recorded, flagOnly) {
  const rows = cur.exists ? prov.get(key) || [] : [];
  const rollSet = new Set(byWriter(rows, ['retention.js']).filter(r => r.kind === 'roll'));
  const insSet = new Set(m.growOnly ? byWriter(rows, INSERT_WRITERS).filter(r => r.kind === 'insert') : []);
  if (!rollSet.size && !insSet.size) return decide(ctx, key, m, b, cur, prov, recorded, flagOnly);
  const rolls = rows.filter(r => rollSet.has(r));
  let u = unwind(ctx, cur, rows.filter(r => rollSet.has(r) || insSet.has(r)));   // in the order they happened
  let tookInserts = insSet.size > 0;
  // an insert that cannot be taken back (someone else wrote the same region since): judge the file as before, rolls only
  if (u.error && insSet.size) { tookInserts = false; if (!rolls.length) return decide(ctx, key, m, b, cur, prov, recorded, flagOnly); u = unwind(ctx, cur, rolls); }
  if (u.error) return { ok: false, act: 'flag', why: 'a retention roll was recorded, but ' + u.error };
  const whole = Object.assign({}, cur, { buf: u.buf, bytes: u.buf.length, sha256: sha(u.buf) });
  const d = decide(ctx, key, m, b, whole, prov, recorded, flagOnly);
  const pre = rolls.length ? 'rolled by retention.js' : '';
  if (d.ok === false) return { ok: false, act: 'flag', why: (pre ? pre + ', but ' : '') + d.why };
  return Object.assign({}, d, { why: [pre ? pre + ' (every archived byte checked)' : '', tookInserts ? 'entries added by ' + INSERT_WRITERS.join('/') + ' (recorded)' : '', d.why].filter(Boolean).join('; ') });
}
function decide(ctx, key, m, b, cur, prov, recorded, flagOnly) {
  if (m.status) {
    if (!cur.exists) return { ok: true, why: 'station-written status removed (the station writes it again)' };
    const bad = statusShape(cur.buf);
    return bad ? { ok: false, act: 'flag', why: 'a station status file now carries ' + bad + ' (it should hold no credential)' } : { ok: true, why: 'station-written status (no credential)' };
  }
  const rows = prov.get(key) || [];
  const W = m.writers || [];
  if (m.cls === 'A' || m.cls === 'R') {
    if (cur.exists && m.append) {
      const from = b.exists ? b.bytes : 0;   // a log created since the last check is tiled from its first byte
      const prefixOk = !b.exists || (cur.bytes >= b.bytes && sha(cur.buf.subarray(0, b.bytes)) === b.sha256);
      if (prefixOk) {
        const t = tile(cur.buf.subarray(from), byWriter(rows, W).filter(r => r.kind === 'append'));
        if (!t.foreign.length) return { ok: true, why: 'appends recorded by ' + W.join('/') };
        if (!b.exists && !t.kept.length) return { ok: false, act: flagOnly ? 'flag' : 'quarantine', why: 'a new log that no ' + W.join('/') + ' write recorded' };
        return { ok: false, act: flagOnly ? 'flag' : 'strip', rebuilt: Buffer.concat([cur.buf.subarray(0, from), t.kept]), why: t.foreign.reduce((n, f) => n + f[1] - f[0], 0) + ' bytes appended that no ' + W.join('/') + ' write recorded' };
      }
      return { ok: false, act: flagOnly ? 'flag' : 'restore', why: 'history before the last check was rewritten' };
    }
    if (cur.exists && byWriter(rows, W).some(r => r.kind === 'write' && r.sha256 === cur.sha256)) return { ok: true, why: 'written by ' + W.join('/') };
    if (cur.exists && recorded && recorded.applied.includes(cur.sha256)) return { ok: true, why: 'an applied harness change' };
    if (cur.exists && b.exists && cur.sha256 === b.sha256) return { ok: true, why: 'mode only' };
    if (cur.exists && ctx.now - cur.mtimeMs >= 0 && ctx.now - cur.mtimeMs < 5000) return { ok: null, why: 'written seconds ago; checked again next tick' };
    if (m.cls === 'R' && m.regen && !flagOnly) return { ok: false, act: 'regen', why: 'not written by ' + W.join('/') };
    if (!b.exists && cur.exists) return { ok: false, act: flagOnly ? 'flag' : 'quarantine', why: 'a new file that no ' + W.join('/') + ' write recorded' };
    return { ok: false, act: flagOnly ? 'flag' : 'restore', why: cur.exists ? 'changed, and no ' + W.join('/') + ' write recorded these bytes' : 'deleted' };
  }
  // F and K: reported, never undone automatically
  if (m.append && cur.exists && b.exists && cur.mode === b.mode && grewFrom(ctx, key, cur, b)) return { ok: true, why: 'appended' };
  // a grow-only record (decisions.md is written newest first): new lines may land anywhere, but every earlier line must
  // still be there, in order. Only removing or rewriting history is a finding.
  if (m.growOnly && cur.exists && b && b.exists) {
    const old = readLkg(ctx, key, b);
    if (old && old !== 'tampered') {
      const was = old.toString('utf8').split('\n'), now = cur.buf.toString('utf8').split('\n');
      let i = 0; for (const l of now) { if (i < was.length && l === was[i]) i++; }
      if (i === was.length && cur.mode === b.mode) return { ok: true, why: 'entries added (grow-only record)' };
    }
  }
  if (m.append && cur.exists && (!b || !b.exists)) return { ok: true, why: 'a new append-only log (accepted; appending is normal)' };   // created after the baseline: seed it, do not re-flag as it grows
  if (cur.exists && W.length && byWriter(rows, W).some(r => r.kind === 'write' && r.sha256 === cur.sha256)) return { ok: true, why: 'written by ' + W.join('/') };
  if (cur.exists && byWriter(rows, ['harness-change.js']).some(r => r.kind === 'write' && r.sha256 === cur.sha256) && recorded && recorded.applied.includes(cur.sha256)) return { ok: true, why: 'an applied harness change' };
  if (cur.exists && recorded && recorded.applied.includes(cur.sha256)) return { ok: true, why: 'an applied harness change' };
  if (recorded && recorded.pending.length && ctx.now - Date.parse(recorded.pending[0].approvedAt) < 20 * 60e3) return { ok: null, why: 'approved change ' + recorded.pending.map(p => p.id).join(', ') + ' is waiting for its apply record' };
  return { ok: false, act: 'flag', why: m.append && cur.exists && b.exists ? 'history before the last check was rewritten' + (m.growOnly ? ' (an entry was edited or removed in place: correct or withdraw one with `node company/tools/decision.js amend|withdraw <id-or-stamp>`, which adds a new entry)' : '') : (m.cls === 'K' ? 'a key or credential changed' : 'changed with no reviewed change or tool record') };
}

