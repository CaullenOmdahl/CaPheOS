function logEvent(ctx, e) { report(ctx, [e], { noHandoffs: true }); }   // people's own accept/revert/undo: in the log, no crew FYI (the risk owner is told separately)
const isOwner = (ctx, o) => { const b = String(o.by || '').trim().toLowerCase(); const on = String(((co.config || {}).owner || {}).name || '').trim().toLowerCase(); return (b === 'owner' || (on && b === on)) && ctx.ownerShell; };
function acceptCmd(ctx, key, o) {
  const base = loadBaseline(ctx); if (!base) throw new Error('no baseline yet (run tick)');
  if (base._tampered && !isOwner(ctx, o)) throw new Error('the baseline is not trustworthy right now; only the owner may accept (or rebuild it)');
  const why = String(o.why || '').trim(); if (why.length < 10) throw new Error('--why must say why the change is meant');
  if (key.startsWith('routine:') || key.startsWith('mode:') || key.startsWith('schedule:')) {
    const m = { owner: key.startsWith('mode:') ? 'risk' : 'tools' }; const p = needPerson(ctx, o.by, key, m, true); verifyRan(ctx, p, ['locked-watch.js', 'accept', key, p.name]);
    if (key.startsWith('mode:')) { const id = key.slice(5); const modes = rosterModes(ctx); base.roster[id] = modes[id]; if (base.rosterFlagged) delete base.rosterFlagged[id]; }
    else if (key.startsWith('schedule:')) { const id = key.slice(9); const r = base.routines && base.routines[id]; if (!r || !r.schedFlagged) throw new Error('nothing flagged for ' + key); r.sched = r.schedFlagged; delete r.schedFlagged; }
    else { const id = key.slice(8); const r = base.routines && base.routines[id]; if (!r || !r.flagged) throw new Error('nothing flagged for ' + key); r.view = r.flagged; delete r.flagged; }
    saveBaseline(ctx, base); logEvent(ctx, { id: evId(ctx), at: local(ctx.now), key, kind: 'accepted', why: why + ' (accepted by ' + p.name + ')', owner: m.owner, area: 'access' }); tellRisk(ctx, 'accepted', key, p, why); return 'accepted ' + key;
  }
  if (key.startsWith('starnet/')) {
    const p = needPerson(ctx, o.by, key, { owner: 'tools' }, true); verifyRan(ctx, p, ['locked-watch.js', 'accept', key, p.name]); const rel = key.slice(8); const sn = starnetState(ctx) || {};
    base.starnet[rel] = sn[rel] || 'clean'; if (base.starnetFlagged) delete base.starnetFlagged[rel];
    if (sn[rel] && sn[rel] !== 'deleted') saveLkg(ctx, key, { cls: 'F' }, stateOf(ctx, key).buf);
    saveBaseline(ctx, base); logEvent(ctx, { id: evId(ctx), at: local(ctx.now), key, kind: 'accepted', why: why + ' (accepted by ' + p.name + ')', owner: 'tools', area: 'starnet' }); tellRisk(ctx, 'accepted', key, p, why); return 'accepted ' + key;
  }
  const m = entryFor(ctx, key); if (!m) throw new Error(key + ' is not a locked file');
  if ((m.cls === 'A' || m.cls === 'R') && !isOwner(ctx, o)) throw new Error(key + ' is written only by ' + (m.writers || []).join('/') + '; only the owner may accept a change to it by hand');
  const p = needPerson(ctx, o.by, key, m, true);
  verifyRan(ctx, p, ['locked-watch.js', 'accept', key, p.name]);
  const b = base.files[key];
  if (p.id !== 'owner' && b && b.flagged && (b.flagged.by || []).includes(p.id)) throw new Error('you cannot accept a change that came from your own run: propose it (node company/tools/harness-change.js) or ask ' + ((ownerOf(ctx, 'risk') || {}).name || 'the risk owner'));
  // whoever accepts must not be the one the watcher attributed the change to, even when the change went through a script (no
  // direct-write row): if a recent agent run of the accepter WROTE this file, they cannot sign it off themselves.
  if (p.id !== 'owner') {
    const self = selfWrite(ctx, p.id, key, ctx.now - 2 * 3600e3);
    if (self) throw new Error(p.name + '\'s own run wrote ' + key + ' (' + self + '): someone else must accept it, or the owner');
  }
  const s = stateOf(ctx, key); accept(ctx, base, key, m, s); saveBaseline(ctx, base);
  logEvent(ctx, { id: evId(ctx), at: local(ctx.now), key, cls: m.cls, kind: 'accepted', why: why + ' (accepted by ' + p.name + ')', owner: m.owner, area: m.area });
  tellRisk(ctx, 'accepted', key, p, why);
  return 'accepted ' + key + ' as the new last-known-good';
}
/* A false name must come off an EXISTING flag without rebuilding the
 * baseline. `baseline --force` is not that — it erases the flag and its record with it. What this does, and all it
 * does: one named agent leaves `flagged.by`. The unaccepted sha stays flagged (that is correct), the last-known-good
 * copy is untouched, and the removal is a sealed log row naming who cleared it and why. Refused when the corrected
 * write record still shows that agent landing bytes on the file: a real write is reviewed and accepted or reverted,
 * never un-attributed. A person cannot clear their own name; the tool's owner, the area owner or the owner does it —
 * the tool's owner on ANY file, because this corrects the watcher's own record, not a permission on the file. */
function clearNameCmd(ctx, key, o) {
  const base = loadBaseline(ctx); if (!base) throw new Error('no baseline yet (run tick)');
  if (base._tampered && !isOwner(ctx, o)) throw new Error('the baseline is not trustworthy right now; only the owner may clear a name');
  const want = String(o.name || '').trim(); if (!want) throw new Error('--name is required: clear-name removes ONE name and says which');
  const why = String(o.why || '').trim(); if (why.length < 10) throw new Error('--why must say why the name was wrong');
  const b = base.files[key];
  if (!b || !b.flagged) throw new Error(key + ' is not flagged: there is no attribution to clear');
  const list = (b.flagged.by || []);
  if (!list.length) throw new Error(key + ' is flagged with no name on it; nothing to clear');
  const named = Object.entries(ctx.agents).find(([, c]) => String((c && c.name) || '').toLowerCase() === want.toLowerCase());
  if (!named) throw new Error('--name ' + want + ' is not someone on the crew');
  const pid = named[0];
  if (!list.includes(pid)) throw new Error(want + ' is not named on ' + key + ' (named: ' + [...new Set(list)].map(x => nameOf(ctx, x)).join(', ') + ')');
  const m = entryFor(ctx, key) || { cls: 'F', owner: 'tools', area: 'tool' };
  let p; try { p = needPerson(ctx, o.by, key, m, true); }
  catch (e) { p = needPerson(ctx, o.by, key, { owner: 'tools' }, true); }   // the tool's owner corrects its own record
  verifyRan(ctx, p, ['locked-watch.js', 'clear-name', key, p.name]);
  if (p.id !== 'owner' && p.id === pid) throw new Error('you cannot clear your own name from a flag: ask the ' + ((ownerOf(ctx, m.owner) || {}).name || 'tooling owner') + ' or the owner to do it');
  const still = selfWrite(ctx, pid, key, Math.max(ctx.now - 4 * 3600e3, 0));
  if (still) throw new Error('the write record still shows ' + want + ' writing ' + key + ' (' + still + ') in the last four hours: a real write is accepted or reverted, not un-attributed');
  const left = list.filter(x => x !== pid);
  b.flagged = Object.assign({}, b.flagged, { by: left, clearedNames: (b.flagged.clearedNames || []).concat([{ name: pid, by: p.id, at: local(ctx.now), why }]) });
  saveBaseline(ctx, base);
  logEvent(ctx, { id: evId(ctx), at: local(ctx.now), key, cls: m.cls, area: m.area, owner: m.owner, kind: 'unattributed', why: why + ' (name cleared by ' + p.name + '; the flag and its last-known-good stay)', who: want, summary: 'still flagged at ' + String(b.flagged.sha256 || '?').slice(0, 20) });
  tellRisk(ctx, 'un-attributed', key, p, why);
  return 'cleared ' + want + ' from ' + key + '\'s attribution; the change stays flagged (' + left.length + ' name(s) left)';
}
function revertCmd(ctx, key, o) {
  const base = loadBaseline(ctx); if (!base) throw new Error('no baseline yet');
  if (key.startsWith('starnet/')) {
    const p = needPerson(ctx, o.by, key, { owner: 'tools' }, true); verifyRan(ctx, p, ['locked-watch.js', 'revert', key, p.name]); const rel = key.slice(8); const was = base.starnet[rel];
    if (!was || was === 'clean') { execFileSync('git', ['-C', ctx.paths.starnet, 'checkout', '--', rel], { stdio: 'ignore' }); }
    else { const lk = readLkg(ctx, key, { lkgSha: was }); if (!lk || lk === 'tampered') throw new Error('no trustworthy last-known-good copy of ' + key); writeAtomic(abs(ctx, key), lk, stateOf(ctx, key).mode || 0o644); }
    if (base.starnetFlagged) delete base.starnetFlagged[rel]; saveBaseline(ctx, base);
    logEvent(ctx, { id: evId(ctx), at: local(ctx.now), key, kind: 'reverted', why: 'put back by ' + p.name, owner: 'tools', area: 'starnet' }); return 'put back ' + key + ' (a running station picks up sidecar changes only after a restart)';
  }
  const m = entryFor(ctx, key); if (!m) throw new Error(key + ' is not a locked file');
  if (m.cls === 'K') throw new Error('keys are never restored from a copy; ask the owner');
  const p = needPerson(ctx, o.by, key, m, true);
  verifyRan(ctx, p, ['locked-watch.js', 'revert', key, p.name]);
  const b = base.files[key]; const lk = readLkg(ctx, key, b);
  if (!lk || lk === 'tampered') throw new Error('no trustworthy last-known-good copy of ' + key);
  writeAtomic(abs(ctx, key), lk, b.mode || 0o644);
  delete b.flagged; saveBaseline(ctx, base);
  logEvent(ctx, { id: evId(ctx), at: local(ctx.now), key, cls: m.cls, kind: 'reverted', why: 'put back to the last-known-good copy by ' + p.name, owner: m.owner, area: m.area });
  return 'put back ' + key;
}
function undoCmd(ctx, id, o) {
  if (!/^lw-\d{12}-[0-9a-z]+$/.test(String(id || ''))) throw new Error('give the event id from the report (lw-…)');
  let all = []; try { all = fs.readFileSync(ctx.paths.report, 'utf8').trim().split('\n').map(l => { try { return JSON.parse(l); } catch (_) { return null; } }).filter(Boolean); } catch (_) {}
  const e = all.find(x => x.id === id && /^(restored|stripped|quarantined)$/.test(x.kind)); if (!e) throw new Error('no automatic revert ' + id);
  const m = entryFor(ctx, e.key); if (!m) throw new Error(e.key + ' is no longer locked');
  let p = { id: 'owner', name: 'owner' };
  if (!isOwner(ctx, o)) { p = needPerson(ctx, o.by, e.key, m, true); verifyRan(ctx, p, ['locked-watch.js', 'undo', id, p.name]); }
  const src = path.join(e.kind === 'quarantined' ? ctx.paths.quarantine : ctx.paths.replaced, id + '-' + flatName(e.key));
  const buf = fs.readFileSync(src);
  const base = loadBaseline(ctx);
  writeAtomic(abs(ctx, e.key), buf, (base.files[e.key] || {}).mode || 0o644);
  accept(ctx, base, e.key, m, stateOf(ctx, e.key)); saveBaseline(ctx, base);
  logEvent(ctx, { id: evId(ctx), at: local(ctx.now), key: e.key, cls: m.cls, kind: 'undone', why: 'automatic revert ' + id + ' undone by ' + p.name + ' (now the last-known-good)', owner: m.owner, area: m.area });
  tellRisk(ctx, 'undone (watcher revert ' + id + ')', e.key, p, 'the watcher had put ' + e.key + ' back; ' + p.name + ' undid that');
  return 'undid ' + id + ': ' + e.key + ' is back as it was before the watcher put it back';
}

// For company/tools/retention.js: run fn while holding the watcher's lock (a tick never sees a roll half done).
function withWatchLock(opts, fn) { return withLock(context(opts), fn); }
// For retention.js, inside withWatchLock: roll the provenance log itself and keep the watcher's byte offset right in the
// same operation. fn({ maxCut }) may move at most the first maxCut bytes (rows the watcher has already read) and returns
// { cut, pointer } (bytes removed from the front, bytes of the pointer line put there) or null. Refused while the
// baseline is not trusted or the log does not match it (the watcher reports that first).
function rebaseProvenance(opts, fn) {
  const ctx = context(opts); const key = 'company/state/locked/provenance.jsonl';
  let base = null; try { base = loadBaseline(ctx); } catch (e) { return { refused: 'the baseline cannot be read: ' + e.message }; }
  if (!base) return { result: fn({ maxCut: Infinity }) };   // no baseline yet: the first tick builds one from what is there
  if (base._tampered) return { refused: 'the watcher\'s baseline is not trusted' };
  const b = base.files[key]; const s = stateOf(ctx, key);
  if (b && b.exists && s.exists && !(s.bytes >= b.bytes && sha(s.buf.subarray(0, b.bytes)) === b.sha256)) return { refused: 'the provenance log does not match the watcher\'s baseline' };
  const off = Number(base.provOffset) || 0;
  const r = fn({ maxCut: off });
  if (!r || !r.cut) return { result: r };
  base.provOffset = Math.max(0, off - r.cut + (r.pointer || 0));
  ctx.now = Date.now();
  accept(ctx, base, key, entryFor(ctx, key) || { cls: 'F' }, stateOf(ctx, key));
  saveBaseline(ctx, base);
  return { result: r, provOffset: base.provOffset };
}
