function provByFile(rows) { const m = new Map(); for (const r of rows) { if (!m.has(r.file)) m.set(r.file, []); m.get(r.file).push(r); } return m; }
// A provenance row is only trusted when nothing about it looks forged. The dispatcher (its ticks run the pacer, competence,
// corrections, model-stats inline) and the owner's own shell are not agent runs, so their rows are trusted. An AGENT run can
// still record its own tool write — my-section.js set, harness-change.js apply — but only when the running program IS that
// writer tool itself: a row an agent recorded from a hand-written script (main = scratch/tidy.js) or from node -e/-r
// (tainted) names a writer the program is not, and is ignored, so a forged record cannot launder a change. Rows with no
// `main` field predate this upgrade (the next baseline rebuild retires them) and stay trusted.
const TOOL_PREFIX = 'company/tools/';
function trustProvRow(row, writers) {
  if (!row || row.tainted === true) return false;
  if (row.main === undefined) return true;   // legacy row
  if (!row.underStation) return true;         // the dispatcher, or the owner's own shell: not an agent run
  const ok = writers.map(w => TOOL_PREFIX + w); ok.push(TOOL_PREFIX + 'dispatch.js');
  return ok.includes(String(row.main));       // an agent run: the program must BE the writer tool it names
}
const byWriter = (rows, writers) => rows.filter(r => writers.some(w => String(r.writer || '').split(' ')[0] === w) && trustProvRow(r, writers));
// the region appended since the baseline, tiled by recorded appends in order; returns the foreign byte ranges
function tile(region, chunks) {
  const used = new Array(chunks.length).fill(false); const kept = []; const foreign = []; let p = 0, fStart = -1;
  const at = pos => { for (let i = 0; i < chunks.length; i++) { if (used[i]) continue; const c = chunks[i]; if (pos + c.chunkBytes <= region.length && sha(region.subarray(pos, pos + c.chunkBytes)) === c.chunkSha) return i; } return -1; };
  while (p < region.length) {
    const i = at(p);
    if (i >= 0) { if (fStart >= 0) { foreign.push([fStart, p]); fStart = -1; } used[i] = true; kept.push(region.subarray(p, p + chunks[i].chunkBytes)); p += chunks[i].chunkBytes; continue; }
    if (fStart < 0) fStart = p;
    const nl = region.indexOf(10, p); p = nl >= 0 ? nl + 1 : region.length;   // foreign bytes end at a line boundary or the end
  }
  if (fStart >= 0) foreign.push([fStart, region.length]);
  return { foreign, kept: Buffer.concat(kept) };
}
// A retention roll (company/tools/retention.js, docs/RETENTION.md) moves old entries of a log into its archive and leaves
// a pointer line. Its provenance row says exactly how: the file it left (sha256/bytes), the file before (beforeSha), and
// where the archived bytes went. unroll() rebuilds the file as if the roll never happened — every archived byte must be
// read back from the archive with its recorded hash — so the usual checks (appends tiled, history unchanged, grow-only)
// run on the whole history. A roll that does not rebuild byte for byte is reported, never accepted, never "repaired".
function unroll(ctx, cur, rolls) { return unwind(ctx, cur, rolls); }
// unwind(ctx, cur, events): take recorded rolls (retention.js) and inserts (decision.js: a new entry at the top of a
// grow-only record) back out of the file, newest first. Each step needs the file to start with exactly the bytes that
// step left (later appends ride along at the end), and must rebuild the recorded file-before byte for byte.
function unwind(ctx, cur, events) {
  let buf = cur.buf;
  for (const r of events.slice().reverse()) {
    if (!(buf.length >= r.bytes) || sha(buf.subarray(0, r.bytes)) !== r.sha256) return { error: r.kind === 'insert' ? 'the file no longer starts with the bytes the ' + String(r.writer || 'insert').split(' ')[0] + ' write left' : 'the file no longer starts with the bytes the roll left' };
    const after = buf.subarray(0, r.bytes), rest = buf.subarray(r.bytes);
    if (r.kind === 'insert') {
      const off = Number(r.offset), n = Number(r.chunkBytes);
      if (!(off >= 0 && n > 0 && off + n <= after.length) || sha(after.subarray(off, off + n)) !== r.chunkSha) return { error: 'the insert record does not match the file' };
      const before = Buffer.concat([after.subarray(0, off), after.subarray(off + n)]);
      if (sha(before) !== r.beforeSha) return { error: 'taking the recorded insert out does not give the file as it was before it' };
      buf = Buffer.concat([before, rest]); continue;
    }
    const pieces = [];
    for (const c of r.chunks || []) {
      // a replaced pointer line: its old text rides in the (trusted) roll row; it can only rebuild the beforeSha below
      if (c.inline != null) { const b = Buffer.from(String(c.inline), 'utf8'); if (b.length > 8192 || sha(b) !== c.sha256) return { error: 'the roll record\'s inline pointer text does not match its hash' }; pieces.push(b); continue; }
      const rel = String(c.archive || '');
      if (!rel.startsWith('company/') || rel.split('/').includes('..') || !/\/archive\//.test(rel)) return { error: 'the roll names an archive outside company/**/archive/ (' + rel.slice(0, 80) + ')' };
      let b; try { const fd = fs.openSync(path.join(ctx.root, rel), 'r'); try { b = Buffer.alloc(c.bytes); const n = fs.readSync(fd, b, 0, c.bytes, c.offset); if (n !== c.bytes) b = null; } finally { fs.closeSync(fd); } } catch (_) { b = null; }
      if (!b || sha(b) !== c.sha256) return { error: 'the archived bytes in ' + rel + ' (offset ' + c.offset + ') are missing or changed' };
      pieces.push(b);
    }
    const stream = Buffer.concat(pieces); const parts = []; let p = 0, sp = 0;
    for (const [at, drop, take] of (r.ops || []).slice().sort((x, y) => x[0] - y[0])) {
      if (at < p || at > after.length) return { error: 'the roll record is malformed' };
      parts.push(after.subarray(p, at)); p = at + drop; parts.push(stream.subarray(sp, sp + take)); sp += take;
    }
    parts.push(after.subarray(Math.min(p, after.length)));
    if (sp !== stream.length) return { error: 'the roll record does not account for every archived byte' };
    const before = Buffer.concat(parts);
    if (sha(before) !== r.beforeSha) return { error: 'live file plus archive do not rebuild the file as it was before the roll' };
    buf = Buffer.concat([before, rest]);
  }
  return { buf };
}
