/* locked-watch.js — notices any change to what measures, limits or protects the crew, and undoes or reports it.
 *
 * Owner direction (three-tier latitude, tier 3 "locked"): an agent never edits what grades or limits it — the
 * pacing policy, the routing table, the competence ledger and policy, performance and correction records, the merge and
 * external gates, keys and access levels, StarNet's own code except through a recorded patch. Everyone runs as one Unix user,
 * so nothing can stop such an edit; this watcher makes every one visible within one dispatcher tick and puts back what only a
 * tool may write. Plain-words guide: company/work/people/LATITUDE.md.
 *
 *   node company/tools/locked-watch.js tick [--dry-run]        compare every locked file with its last-known-good, act, report
 *   node company/tools/locked-watch.js status                  what is watched, open flags
 *   node company/tools/locked-watch.js revert <path> --by <Name>                put the last-known-good copy back (flagged files)
 *   node company/tools/locked-watch.js accept <path> --by <Name> --why "…"      take the change as the new last-known-good
 *   node company/tools/locked-watch.js undo <event id> --by <Name>              undo one of the watcher's own automatic reverts
 *   node company/tools/locked-watch.js baseline [--force]                       (re)build the baseline (the first tick does it)
 *   node company/tools/locked-watch.js selftest
 *
 * What happens to a change (classes in the MANIFEST below):
 *   A  only a recording tool writes it (corrections.js, competence.js, pacer.js, my-section.js, harness-change.js,
 *      premerge-check.js, the dispatcher). A change whose bytes match a write the tool recorded (company/tools/provenance.js)
 *      is accepted. Anything else is put back from the last-known-good copy (an append-only log keeps every recorded append
 *      and loses only the foreign bytes; a new file nobody recorded is moved to quarantine). Undo: `undo <event id>`.
 *   R  generated: regenerated by its generator (competence.js compute/scoreboard, model-stats.js).
 *   F  people may legitimately change it (a reviewed, applied harness change; hire.js for the crew list; the owner): a change
 *      with no record is reported, never undone automatically, with the one command that undoes it. Append-only logs with many
 *      writers (decisions.md, dispatch-log.md, ...) are only checked for rewritten history.
 *   K  keys and the station's environment: hash and file mode only, never copied, never printed; any change is reported.
 *   Also: StarNet's own code (a change is accepted when a record in company/patches/ that names the file changed with it),
 *   routines' Commander-only fields (grants, workdir, skills, script, context, noAgent), agents' approval modes, and the
 *   station's connectors and GitHub service keys against the scope in company/tools/connector-scope.js (POLICY; the
 *   external-capability inventory): a connector out of scope is reported to the risk owner once per change, never changed
 *   by the watcher.
 * The harnessSelfEdit guardrail off (company/state/guardrails.json): every change is recorded as "drift" in the report log
 * and becomes the last-known-good; nothing is put back and nobody is flagged. guardrails.json itself is always watched.
 * Who did it: provenance rows, then agent runs' transcripts (only the tool calls: tool name, path, agent, run and time; never
 * the content, never the owner's chats), then the runs active at the time. --by claims of my-section.js and harness-change.js
 * are checked against the transcripts: a claim made from another agent's run is reported (and an own section changed that way
 * is put back); a claim no transcript shows yet is kept pending (the run's tool calls reach the transcript after the tool
 * wrote its claim) and re-checked each tick, flagged "no run of X shows this command" only if still unmatched 30 minutes on
 * with no run of X in flight. StarNet's runs.jsonl (bigAppend) is checked incrementally: the first 64 KB and the 64 KB
 * before the last checked end unchanged, the rest new; it is never hashed whole and no copy of it is kept.
 * Reports: a DONE FYI handoff to the seat that holds the file's function (owner field below: people, tools, risk, finance,
 * ceo — resolved through company/tools/lib/company.js, so it follows whoever holds the seat), the risk owner too for gates,
 * keys, access and StarNet, and
 * company/work/security/locked-changes.jsonl + .md.
 * Last-known-good copies and the baseline: company/state/locked/ (secrets are never copied); the baseline's hash is mirrored in
 * ~/.local/share/capheos-guard/<company slug>/locked-baseline.sha256, and a baseline that does not match it turns automatic reverts off.
 * Wiring: dispatch.js runs tick() every 10 minutes, before it reads its own state. Owner of this tool: the tools owner
 * (co.seatFor('tools')); its reports also go to the risk owner (co.seatFor('risk')).
 */
